import { createRequire } from 'module';
const U = createRequire(import.meta.url)('../unidades.js');
const q = (n, u) => U.mul(n, U.de(u));
let fallos = 0;
const t = (nombre, f, esp, tol) => {
  let r; try { r = f(); if (U.esQ(r)) r = U.texto(r); } catch (e) { r = 'ERR:' + e.message; }
  const ok = tol ? Math.abs(r - esp) <= tol : r === esp;
  console.log((ok ? '✅ ' : '❌ ') + nombre + ' → ' + r + (ok ? '' : '   (esperado ' + esp + ')'));
  if (!ok) fallos++;
};
const m2 = () => U.pow(U.de('m'), 2);
t('10 kN', () => q(10, 'kN'), '10 kN');
t('(10 kN)*(2 m)', () => U.mul(q(10, 'kN'), q(2, 'm')), '20 kN·m');
t('10 kN a N', () => U.aUnidad(q(10, 'kN'), U.de('N')), '10000 N');
t('(20 kN·m)/(4 m)', () => U.div(U.mul(q(20, 'kN'), q(1, 'm')), q(4, 'm')), '5 kN');
t('3 m + 2 mm', () => U.add(q(3, 'm'), q(2, 'mm')), '3.002 m');
t('3 m + 2 mm a mm', () => U.aUnidad(U.add(q(3, 'm'), q(2, 'mm')), 'mm'), '3002 mm');
t('3 m + 2 kg', () => U.add(q(3, 'm'), q(2, 'kg')), 'ERR:unidades incompatibles: m + kg');
t('3 m − 2 kg', () => U.sub(q(3, 'm'), q(2, 'kg')), 'ERR:unidades incompatibles: m + kg');
t('10 kN + 1', () => U.add(q(10, 'kN'), 1), 'ERR:unidades incompatibles: kN + 1');
t('0 − 5 kN', () => U.sub(0, q(5, 'kN')), 'ERR:unidades incompatibles: 1 + kN');
t('sqrt(4 m²)', () => U.sqrt(U.mul(4, m2())), '2 m');
t('30 tonf a kN', () => U.aUnidad(q(30, 'tonf'), 'kN'), '294.2 kN');
t('(30 tonf)/(4 m²) a kPa', () => U.aUnidad(U.div(q(30, 'tonf'), U.mul(4, m2())), 'kPa'), '73.5499 kPa');
t('num(30 deg)', () => U.num(q(30, 'deg')), Math.PI / 6, 1e-12);
t('sin(num(30 deg))', () => Math.sin(U.num(q(30, 'deg'))), 0.5, 1e-12);
t('F/F', () => U.div(q(7, 'kN'), q(7, 'kN')), 1);
t('(6 m)/(3 mm)', () => U.div(q(6, 'm'), q(3, 'mm')), 2000, 1e-9);
t('(2 m)*(3 mm)', () => U.mul(q(2, 'm'), q(3, 'mm')), '0.006 m²');
t('(10 kN)^2', () => U.pow(q(10, 'kN'), 2), '100 kN²');
t('2/m', () => U.div(2, U.de('m')), '2 1/m');
t('10 kN a m', () => U.aUnidad(q(10, 'kN'), U.de('m')), 'ERR:unidades incompatibles: kN → m');
t("de('xyz')", () => U.de('xyz'), 'ERR:unidad desconocida: xyz');
t('max(3 m, 200 mm)', () => U.max(q(3, 'm'), q(200, 'mm')), '3 m');
t('max(3 m, 4 kN)', () => U.max(q(3, 'm'), q(4, 'kN')), 'ERR:max: unidades incompatibles');
t('min(3 m, 200 mm)', () => U.min(q(3, 'm'), q(200, 'mm')), '200 mm');
t('cmp(5 kN, 3 m)', () => U.cmp(q(5, 'kN'), q(3, 'm')), 'ERR:unidades incompatibles al comparar');
t('cmp(3 m, 200 mm)', () => U.cmp(q(3, 'm'), q(200, 'mm')), 1);
t('igual(1 m, 1000 mm)', () => U.igual(q(1, 'm'), q(1000, 'mm')), true);
t('igual(1 m, 1 kg)', () => U.igual(q(1, 'm'), q(1, 'kg')), false);
t('num(10 kN)', () => U.num(q(10, 'kN')), 'ERR:tiene unidades (10 kN); quítalas dividiendo por la unidad');
t('kN/N → 1000', () => U.div(U.de('kN'), U.de('N')), 1000);
t('1 gal a qt', () => U.aUnidad(q(1, 'gal'), 'qt'), '4 qt');
t('1 gal a L', () => U.aUnidad(q(1, 'gal'), 'L'), '3.78541 L');
t('60 mph a km/h', () => U.aUnidad(q(60, 'mph'), 'km/h'), '96.5606 km/h');
t('1 hp a W', () => U.aUnidad(q(1, 'hp'), 'W'), '745.7 W');
t('1 psi a kPa', () => U.aUnidad(q(1, 'psi'), 'kPa'), '6.89476 kPa');
t('1000 rpm a Hz', () => U.aUnidad(q(1000, 'rpm'), 'Hz'), '16.6667 Hz');
t('1 cal a J', () => U.aUnidad(q(1, 'cal'), 'J'), '4.184 J');
t('981 Gal a gn', () => U.aUnidad(q(981, 'Gal'), 'gn'), '1.00034 gn');
t('1 mi a km', () => U.aUnidad(q(1, 'mi'), 'km'), '1.60934 km');
console.log(fallos ? `\n${fallos} FALLOS` : '\nTodo OK');
process.exit(fallos ? 1 : 0);
